# VERIFY (T6): renders logs/regression_pilot.md from the files the regression scripts wrote (every number is read from a file or computed here).
# Written 2026-11-11 by pkg:VERIFY. Standard library only. Run after run_all_verify.sh: python3 -I -B harness/controls/make_regression_report.py
import collections, csv, datetime, glob, gzip, json, os, re, subprocess, sys

HERE = os.path.dirname(os.path.abspath(__file__)); S = os.path.dirname(os.path.dirname(HERE))
P = os.path.join(os.path.dirname(os.path.dirname(S)), 'pilots', 'r3')
L = os.path.join(S, 'logs', 'regression')
sys.path.insert(0, os.path.join(S, 'harness'))


def tsv(p):
    return list(csv.DictReader(open(p, encoding='utf-8'), delimiter='\t'))


def main():
    now = datetime.datetime.now().astimezone().strftime('%Y-%m-%d %H:%M %Z')
    cnt = json.load(open(os.path.join(L, 'regression_counts.json')))
    comp = {t: tsv(os.path.join(L, 'comparison_%s.tsv' % t)) for t in ('E1', 'E2')}
    attr = tsv(os.path.join(L, 'attribution_comparison.tsv'))
    rec = tsv(os.path.join(L, 'record_level.tsv'))
    summ = json.load(open(os.path.join(L, 'results', 'summary.json')))
    pil = json.load(open(os.path.join(P, 'results', 'summary.json')))
    extra = open(os.path.join(L, 'extra_facts.txt'), encoding='utf-8').read()
    rows = [json.loads(l) for l in open(os.path.join(L, 'results', 'per_program.jsonl'))]
    out = []
    w = out.append
    w('# Pilot regression test of the new harness (STAGE2 T6)')
    w('')
    w('Written %s by pkg:VERIFY. **pilot regression, not study data.** Generated by `harness/controls/make_regression_report.py` from the files under `logs/regression/` (every count below is read from a file written by a script).' % now)
    w('')
    w('## 1. What was run')
    w('- Inputs: the pilot fixtures (3 CSV files) and the pilot\'s 480 main programs (`qwen35_9b` and `sonnet55`, t01-t48 x s0-s4), copied byte for byte into `logs/regression/inputs/` (sha256 list `INPUTS.sha256`; the pilot folder was only read). Pilot programs have no specification cards, so every program is classified with an unflagged card (stratum `A`, no order or dtype flag). Program ids are `gen/pilot_<model>/<task>__s<k>` (not `pilot/...` as in CONVENTIONS 3.4) so that `analyze_full.py` can read them (deviation V1).')
    w('- Harness: the new study harness (`harness/run_programs.py`, `oracle.py`, `warndef.py`, `attribution.py`, `analyze_full.py`) after the fixes of `harness/HARNESS_FIXES.md`. Configs E0a, E0b (PYTHONHASHSEED=1), E1 (pandas 3.1.1), E2 (pandas 3.0.6) for all 480 programs; A1-A4 and the line traces T0, T1, T2 for the programs that drift on E1 or E2 (selected by the new oracle: `inputs/jobs_drift.jsonl`). 2 workers, 2 GB limit per run, sandbox and limits of section 6. Run records: `logs/regression/runs/`.')
    base = [r for r in rows]
    w('- Run records written: %s; statuses and checks are in `stage1_console_2026-11-11.txt` and `stage2_console_2026-11-11.txt`.' % sum(1 for _ in glob.glob(os.path.join(L, 'runs', '*', 'gen', '*', '*.json.gz')) if not _.endswith(('.result.json.gz', '.trace.json.gz'))))
    hs = collections.Counter()
    for f in glob.glob(os.path.join(L, 'runs', '*', 'gen', '*', '*.json.gz')):
        if f.endswith(('.result.json.gz', '.trace.json.gz')):
            continue
        hs[json.load(gzip.open(f, 'rt'))['harness_sha256'][:12]] += 1
    w('- `harness_sha256` values in the run records: %s.' % dict(hs))
    w('- Not covered, by scope: E3/E4 (pilot has them; T6 names E0a, E0b, E1, E2), V-clean/V-dirty, exposure scan (no exposure table exists yet), harm pre-label (pilot has no references).')
    w('')
    w('## 2. Result')
    for t, pair in (('E1', 'E0a~E1'), ('E2', 'E0a~E2')):
        m = cnt['matrices'][t]
        w('**%s (%s)**: of %d programs, %d have the same class as the pilot when the new records are classified with the pilot definitions (pilot warning definition, pilot order and dtype rule), and %d when they are classified with the section 3 definitions (unflagged cards). Differences to the pilot: %s (pilot definitions), %s (section 3 definitions).'
          % (t, pair, cnt['counts']['programs_' + t], cnt['counts']['same_pilotdef_' + t], cnt['counts']['same_study_' + t],
             len(m['pilot_vs_new_pilotdef']) or 'none', len(m['pilot_vs_new_study']) or 'none'))
        w('')
        w('| class | pilot | new, pilot definitions | new, section 3 definitions |')
        w('|---|---|---|---|')
        keys = sorted(set(m['class_counts_pilot']) | set(m['class_counts_new_pilotdef']) | set(m['class_counts_new_study']))
        for k in keys:
            w('| %s | %s | %s | %s |' % (k, m['class_counts_pilot'].get(k, 0), m['class_counts_new_pilotdef'].get(k, 0), m['class_counts_new_study'].get(k, 0)))
        w('')
    w('Program-by-program lists: `comparison_E1.tsv`, `comparison_E2.tsv` (columns pilot, new_pilotdef, new_study, oracle class, magnitude, silent flag, causes). `differences.tsv` holds every program whose section 3 class differs from the pilot class: **%d programs**.' % len(tsv(os.path.join(L, 'differences.tsv'))))
    unexpl = [r for t in comp for r in comp[t] if 'UNEXPLAINED' in (r['cause_pilotdef_vs_pilot'] + r['cause_study_vs_pilotdef'])]
    w('Unexplained differences: **%d**.' % len(unexpl))
    w('')
    w('Oracle detail for the drift programs (new oracle, unflagged cards): ')
    for t in ('E1', 'E2'):
        c = collections.Counter((r['study_class_oracle'], r['magnitude'], r['silent_primary']) for r in comp[t] if r['study_class_oracle'] in ('VALUE_DRIFT', 'NO_RESULT', 'ORDER_DRIFT', 'DTYPE_DRIFT'))
        w('- %s: %s (class, magnitude, primary silent flag: count)' % (t, ', '.join('%s/%s/%s: %d' % (k + (v,)) for k, v in sorted(c.items(), key=str))))
    w('')
    w('## 3. Record level (stricter than the class comparison)')
    nd = [r for r in rec if r['differences']]
    w('`harness/controls/reg_records.py` compares each of the %d new records (480 programs x E0a, E0b, E1, E2) with the pilot record of the same program and config: status, canonical result, result dtypes, result type, versions (python, pandas, numpy, pyarrow) and the set of user-phase pandas warnings (category, masked message, program line) under both the pilot and the section 3 definitions. Records with any difference: **%d**. Control of the check itself (`record_level_summary.txt`): %s.' % (len(rec), len(nd), open(os.path.join(L, 'record_level_summary.txt')).read().strip().splitlines()[-1]))
    w('')
    w('## 4. Causes the task asked to check')
    w('Facts below are copied from `extra_facts.txt` (script `reg_extra.py`).')
    w('')
    w('```')
    w(extra.strip())
    w('```')
    w('')
    w('- **Versions of the pilot venvs vs the study venvs.** The sorted package lists `pilots/r3/envs/{pd233,pd311,pd306}.freeze.txt` and `envs/{pd233,pd31x,pd30x}.freeze.txt` are identical (checked with `diff`), and the version records above agree (CPython 3.12.13, NumPy 2.5.4, pandas 2.3.3 / 3.1.1 / 3.0.6). There is therefore no NumPy or other version difference to explain.')
    w('- **E0b hash seed.** The pilot ran E0b with PYTHONHASHSEED=0 like E0a; the new E0b uses 1 (records show `py_hash_seed_env` 0 for E0a and 1 for E0b). Result: no program has a different canonical result or dtype record between E0a and E0b, so no program changes its exclusion status (EXCL_NONDET is 0 in the pilot and 0 here). The cause is real but has no effect on this program set.')
    w('- **Warning definition (section 3 vs pilot).** The section 3 definition excludes NumPy-originated messages (the "generic unit" DeprecationWarning) that the pilot definition counted as pandas warnings. It changes `warned_E0a` for the programs listed under heading 3 of the facts above and no class on E1 or E2; the pilot-definition and section 3 classes are equal for all 480 programs on both targets.')
    w('- **Attribution labels.** Comparison of the new primary label with the pilot label through `harness/pilot_label_map.tsv` (`attribution_comparison.tsv`):')
    ca = collections.Counter((r['target'], r['agree_primary']) for r in attr)
    for t in ('E1', 'E2'):
        w('  - %s: %d drift programs, primary label agrees for %d, differs for %d; the pilot label is among the new labels for %d.' % (
            t, sum(v for (tt, a), v in ca.items() if tt == t), ca.get((t, 'True'), 0), ca.get((t, 'False'), 0),
            sum(1 for r in attr if r['target'] == t and r['agree_any_label'] == 'True')))
    wo = {}
    for m_ in re.finditer(r"differs with T2: \('([^']+)', '([^']*)', '([^']+)', '([^']+)', '([^']+)', '([^']+)', (True|False)\)", extra):
        wo[m_.group(1)] = m_.groups()
    for r in attr:
        if r['agree_primary'] != 'True':
            g = wo.get(r['program_id'])
            txt = ('  - differs: `%s` %s: pilot label %s, new primary %s (labels %s, step %s).' % (r['program_id'], r['target'], r['pilot_label'], r['new_primary'], r['new_labels'], r['step']))
            if g:
                txt += (' The pilot ran no 3.0.x line trace: for any target other than E1 it skipped the divergent-line level and used the 2.3.3 warnings and then the program text (pilot `analyze.py` `attribute`, `div = ... if target == \'E1\' else None`), where its GROUPBY_APPLY rule is the regex `\\.apply\\(` (any call of .apply). Re-attributing the same program WITHOUT the T2 trace with the new harness gives `%s` (step %s; agrees with the pilot label through the map: %s); with the T2 trace the first divergent line decides (`%s`, step %s). ' % (g[4], g[5], g[6], g[2], g[3]))
            if g and g[6] == 'False':
                txt += 'The difference therefore remains without the trace: the pilot rule labels any `.apply(` call GROUPBY_APPLY (this program calls Series.apply and DataFrame.apply, not groupby.apply), while the study rule table (catalogue ids) has no rule for a plain apply and labels the Period end_time use D03, which is also the family of the pilot\'s own E1 label for this program (DT_UNIT). A label-definition difference, not a harness defect.'
            w(txt)
    tr = collections.Counter(r['truncated'] for r in attr)
    w('  - Trace truncation flag among the drift programs: %s (pilot: t08__s1 truncated by the 60 s limit; after fix F3 the new trace run also ends truncated instead of being killed).' % dict(tr))
    w('')
    w('## 5. End-to-end analyzer on the regression records')
    w('`analyze_full.py` (real oracle and attribution) wrote `logs/regression/results/{per_program.jsonl, summary.json, hypotheses.md}`; `summary.json` and `hypotheses.md` carry the label "%s" (per_program.jsonl is a plain JSON-lines file; the label is in `results/LABEL.txt`). `decision.py` on that summary prints **%s** (no study models), see `decision_cli_2026-11-11.txt`.' % (summ['label'], summ['decision']['status']))
    w('')
    w('| quantity | pilot `results/summary.json` | new `summary.json` |')
    w('|---|---|---|')
    for m, pm in (('pilot_qwen35_9b', 'qwen35_9b'), ('pilot_sonnet55', 'sonnet55')):
        e = summ['targets']['E0a~E1']['rates'][m]['A']
        pe = pil[pm]['E1']
        w('| %s clean programs | %s | %s |' % (pm, pe['n_clean'], e['n']))
        w('| %s silent drift (primary pair) | %s | %s |' % (pm, pe['silent'], e['x']))
    w('')
    w('The new analyzer counts SUBSTANTIVE drift without a section 3 pandas warning as silent; all drift programs of this set are SUBSTANTIVE (above), so the counts agree with the pilot\'s.')
    w('')
    w('## 6. Disk')
    du = subprocess.run(['du', '-sh', L], capture_output=True, text=True).stdout.split()[0]
    w('`du -sh logs/regression` = %s.' % du)
    open(os.path.join(S, 'logs', 'regression_pilot.md'), 'w', encoding='utf-8').write('\n'.join(out) + '\n')
    open(os.path.join(L, 'results', 'LABEL.txt'), 'w').write('pilot regression, not study data\n')
    print('wrote logs/regression_pilot.md')


if __name__ == '__main__':
    sys.exit(main())
