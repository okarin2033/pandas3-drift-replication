# VERIFY (T5.11, P-): evaluate the negative / matching-positive / magnitude controls against the expectations written in controls.json.
# Written 2026-11-11 by pkg:VERIFY. Standard library only. Run:
#   python3 -I -B harness/controls/pminus_eval.py [--results logs/controls/pminus/results] [--out logs/controls/pminus_eval_<date>.md]
# Each control is scored on E0a~E1 (required) and reported on E0a~E2 (information). A control passes when the oracle class is in the
# expected set, drift equals the expectation, the magnitude class equals the expectation, and (natural controls) the pilot-rule class
# equals the expected one. A control whose raw cross-version difference is not the intended one is a defect of the control, listed apart.
import argparse, json, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
S = os.path.dirname(os.path.dirname(HERE))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--results', default=os.path.join(S, 'logs', 'controls', 'pminus', 'results'))
    ap.add_argument('--out', default=None)
    ap.add_argument('--json', default=None)
    a = ap.parse_args()
    ctl = json.load(open(os.path.join(HERE, 'controls.json'), encoding='utf-8'))['controls']
    pp = {}
    for ln in open(os.path.join(a.results, 'per_program.jsonl'), encoding='utf-8'):
        r = json.loads(ln)
        pp[r['task_id']] = r
    rows, fails = [], []
    for c in ctl:
        r = pp.get(c['name'])
        for pair in ('E0a~E1', 'E0a~E2'):
            t = (r or {}).get('targets', {}).get(pair)
            ok, why = True, []
            if r is None or t is None:
                ok, why = False, ['missing']
            else:
                if not r['clean_on_233']:
                    ok = False; why.append('excluded: %s' % r.get('exclusion_detail'))
                if t['class'] not in c['expect_class']:
                    ok = False; why.append('class %s not in %s' % (t['class'], c['expect_class']))
                if c['expect_drift'] is not None and bool(t['drift']) != c['expect_drift']:
                    ok = False; why.append('drift %s, expected %s' % (t['drift'], c['expect_drift']))
                if c['expect_drift'] is not None and t['magnitude'] != c['expect_magnitude']:
                    ok = False; why.append('magnitude %s, expected %s' % (t['magnitude'], c['expect_magnitude']))
                if c.get('expect_class_pilot_rule') and t['class_pilot_rule'] != c['expect_class_pilot_rule']:
                    ok = False; why.append('pilot-rule class %s, expected %s' % (t['class_pilot_rule'], c['expect_class_pilot_rule']))
            scored = c['scored'] and pair == 'E0a~E1'
            rows.append({'name': c['name'], 'kind': c['kind'], 'category': c['category'], 'pair': pair, 'scored': scored,
                         'cls': (t or {}).get('class'), 'drift': (t or {}).get('drift'), 'mag': (t or {}).get('magnitude'),
                         'pilot': (t or {}).get('class_pilot_rule'), 'expect': '/'.join(c['expect_class']), 'ok': ok, 'why': '; '.join(why),
                         'first_diff': ((t or {}).get('first_diff') or {}).get('kind')})
            if scored and not ok:
                fails.append(c['name'])
    sc = [x for x in rows if x['scored']]
    neg = [x for x in sc if not x['drift'] and x['expect'] and not x['expect'].startswith(('ORDER_DRIFT', 'DTYPE_DRIFT', 'VALUE_DRIFT', 'NO_RESULT'))]
    # specificity: controls whose expectation is non-drift; matching positives: expectation is drift
    exp_nd = [x for x in sc if not _expect_drift(ctl, x['name'])]
    exp_d = [x for x in sc if _expect_drift(ctl, x['name'])]
    L = ['# P- evaluation (negative, matching-positive and magnitude controls)', '',
         'Generated by harness/controls/pminus_eval.py from %s' % os.path.relpath(a.results, S), '',
         'Scored controls on E0a~E1: %d, passed %d (%.1f%%).' % (len(sc), sum(1 for x in sc if x['ok']), 100.0 * sum(1 for x in sc if x['ok']) / max(1, len(sc))),
         'Specificity (expected non-drift controls classified non-drift as expected): %d of %d.' % (sum(1 for x in exp_nd if x['ok']), len(exp_nd)),
         'Sensitivity on matching positives and drift-magnitude cases (expected drift, class and magnitude exact): %d of %d.' % (sum(1 for x in exp_d if x['ok']), len(exp_d)),
         '', '| control | kind | pair | scored | class | expected | drift | magnitude | pilot-rule class | first diff | ok | note |', '|---|---|---|---|---|---|---|---|---|---|---|---|']
    for x in rows:
        L.append('| %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s | %s |' % (x['name'], x['kind'], x['pair'], 'yes' if x['scored'] else 'info',
                                                                                   x['cls'], x['expect'], x['drift'], x['mag'], x['pilot'], x['first_diff'], x['ok'], x['why']))
    text = '\n'.join(L) + '\n'
    if a.out:
        open(a.out, 'w', encoding='utf-8').write(text)
    if a.json:
        json.dump({'scored': len(sc), 'passed': sum(1 for x in sc if x['ok']), 'specificity': [sum(1 for x in exp_nd if x['ok']), len(exp_nd)],
                   'sensitivity': [sum(1 for x in exp_d if x['ok']), len(exp_d)], 'fails': fails, 'rows': rows}, open(a.json, 'w'), indent=1)
    print('\n'.join(L[4:7]))
    print('FAILS: %s' % (fails or 'none'))
    return 0 if not fails else 1


def _expect_drift(ctl, name):
    for c in ctl:
        if c['name'] == name:
            return bool(c['expect_drift'])
    return False


if __name__ == '__main__':
    sys.exit(main())
